"""Expected arm counts per rung (final-review ruling C2b), hand-computed.

Survival model: in each group, every non-protected arm is a quota winner with probability
``min(1, ceil(n / eta) / n)`` times its own presence probability, independently. An expansion
arm generated by several possible winners is present with ``1 - prod(1 - p_winner)``.
"""

import pytest

from resetsweep.sweep.arms import DENSE_TASKS, Arm, arm_space
from resetsweep.sweep.ladder import project_ladder

TASK_A = "acrobot_swingup_sparse"


def _arm(label: str) -> Arm:
    (match,) = [a for a in arm_space("rung0") if a.label() == label]
    return match


ACRO_TRIO = [
    _arm(f"{TASK_A}/uniform/-"),
    _arm(f"{TASK_A}/point/-"),
    _arm(f"{TASK_A}/walk[p_task=0.5]/rnd"),
]
MAZE_TRIO = [_arm("maze/uniform/-"), _arm("maze/point/-"), _arm("maze/walk[p_task=0.5]/rnd")]


def test_acrobot_trio_hand_computed() -> None:
    # Rung 0: 3 arms. One non-protected arm -> quota 1 -> walk wins surely.
    # Rung 1: uniform, point, walk at p_task 0.5/0.2/0.8 = 5 arms.
    # Rung 2: quota ceil(3/3) = 1 of 3 walks -> each wins with 1/3.
    #   protected 2 + walks 3 * 1/3 = 1 + inverted 3 * 1/3 = 1 (acrobot) = 4 on acrobot;
    #   each dense task: 3 distinct walk copies * 1/3 = 1, plus uniform and point each present
    #   with 1 - (2/3)^3 = 19/27.
    ladder = project_ladder(ACRO_TRIO, eta=3)

    assert ladder.totals() == pytest.approx((3.0, 5.0, 4.0 + 3 * (1.0 + 2 * 19 / 27)))
    assert ladder.per_rung[2][TASK_A] == pytest.approx(4.0)
    for task in DENSE_TASKS:
        assert ladder.per_rung[2][task] == pytest.approx(1.0 + 38 / 27)


def test_maze_trio_dedupes_dense_copies_across_groups() -> None:
    # Rung 1: maze (u, p, walk 0.5/0.2/0.8) = 5; maze[lanes=5] (u, p, walk) = 3 -> 8.
    # Rung 2: maze walks win with 1/3 each; the lanes=5 walk is its group's only contender -> 1.
    #   maze: 2 + 1 + inverted 1 = 4; maze[lanes=5]: 3 + inverted 1 = 4.
    #   Dense walk p_task=0.5 comes from maze (1/3) or lanes=5 (1): present with 1. p_task 0.2
    #   and 0.8 copies: 1/3 each -> 5/3 per dense task, plus 2 anchors (surely) -> 11 in all.
    ladder = project_ladder(MAZE_TRIO, eta=3)

    assert ladder.totals() == pytest.approx((3.0, 8.0, 4.0 + 4.0 + 3 * (5 / 3) + 6.0))


def test_full_rung0_projection_counts_rung0_exactly() -> None:
    rung0 = arm_space("rung0")

    ladder = project_ladder(rung0, eta=3)

    assert ladder.totals()[0] == len(rung0) == 704
    # Rung 1, per sparse group: 2 anchors + quota ceil(62/3) = 21 winners + 2 p_task variants
    # for each of the 57 non-visited contenders, each a winner with 21/62. Task variants:
    # maze[lanes=5] gets 62 * 21/62 = 21 walk-ins and 2 anchors (present with P), each of the two
    # maze_trap variants the same. P = 1 - (41/62)^62.
    p_any = 1 - (41 / 62) ** 62
    expected = 11 * (2 + 21 + 57 * 2 * 21 / 62) + 3 * (21 + 2 * p_any)
    assert ladder.totals()[1] == pytest.approx(expected)
    assert all(t > 0 for t in ladder.totals())


def test_one_rung_projection_is_rung0_only() -> None:
    assert project_ladder(ACRO_TRIO, eta=3, n_rungs=1).totals() == (3.0,)


def test_rejects_bad_eta_and_empty_arms() -> None:
    with pytest.raises(ValueError, match="eta"):
        project_ladder(ACRO_TRIO, eta=1)
    with pytest.raises(ValueError, match="empty"):
        project_ladder([], eta=3)
